import { expect, test } from '@playwright/test';

test('interessado, reserva vinculada e parcela persistem no banco isolado', async ({ page }) => {
  await page.goto('/login');
  await page.getByLabel('E-mail').fill('e2e@example.test');
  await page.getByLabel('Senha', { exact: true }).fill('senha-e2e-123');
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard/);
  await page.goto('/leads');
  await page.getByRole('button', { name: 'Novo interessado' }).click();
  const dialog = page.getByRole('dialog');
  await dialog.locator('#lead-name').fill('Pessoa de teste E2E');
  await dialog.getByLabel('Telefone').fill('83999990000');
  await dialog.getByRole('button', { name: 'Salvar', exact: true }).click();
  const card = page.locator('article').filter({ hasText: 'Pessoa de teste E2E' });
  await expect(card).toBeVisible();
  await card.getByRole('button', { name: 'Editar' }).click();
  await dialog.locator('#lead-name').fill('Pessoa editada E2E');
  await dialog.getByLabel('Etapa').selectOption('CONTACTED');
  await dialog.getByRole('button', { name: 'Salvar', exact: true }).click();
  await page.reload();
  const updated = page.locator('article').filter({ hasText: 'Pessoa editada E2E' });
  await expect(updated).toBeVisible();
  await expect(updated).toContainText('Contato realizado');
  await expect(page.getByText('Pessoa de teste E2E', { exact: true })).toHaveCount(0);

  await page.goto('/reservations');
  await page.getByRole('button', { name: 'Nova reserva' }).click();
  const trip = page.locator('#res-trip');
  await expect(trip.getByRole('option', { name: 'Viagem fictícia E2E' })).toBeAttached();
  await trip.selectOption({ label: 'Viagem fictícia E2E' });
  const lead = page.locator('#res-lead');
  await expect(lead.getByRole('option', { name: 'Pessoa editada E2E' })).toBeAttached();
  await lead.selectOption({ label: 'Pessoa editada E2E' });
  await page.locator('#res-name').fill('Responsável E2E');
  await page.locator('#res-total').fill('250,00');
  await page.getByRole('button', { name: 'Cadastrar reserva' }).click();
  const reservation = page.locator('article').filter({ hasText: 'Responsável E2E' });
  await expect(reservation).toContainText('Interessado: Pessoa editada E2E');
  await expect(reservation).toContainText('250,00');
  await reservation.getByRole('button', { name: 'Adicionar parcela' }).click();
  await reservation.locator('input[id^="amount-"]').fill('100,00');
  await reservation.locator('input[id^="due-"]').fill('2030-01-10');
  await reservation.getByRole('button', { name: 'Salvar parcela' }).click();
  await expect(reservation).toContainText('100,00');
  await reservation.getByRole('button', { name: 'Registrar recebimento' }).click();
  await expect(reservation).toContainText('Recebida');
  await page.reload();
  await expect(reservation).toContainText('Interessado: Pessoa editada E2E');
  await expect(reservation).toContainText('250,00');
  await expect(reservation).toContainText('100,00');
  await expect(reservation).toContainText('Vencimento: 10/01/2030');
  await expect(reservation).toContainText('Recebida');
});
